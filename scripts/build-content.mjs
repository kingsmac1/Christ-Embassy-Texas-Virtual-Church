// Generates src/data/content.ts from my-site-reference/content-json (the WordPress page export).
// Each page is an array of sections; each section is an ordered list of blocks. Image URLs are mapped
// to the local copies in /public/images. Run: node scripts/build-content.mjs
import fs from "fs";
const R = "my-site-reference";
const imgMap = JSON.parse(fs.readFileSync(`${R}/images-map.json`, "utf8")).map;
const localize = (u) => {
  const name = imgMap[u] ?? imgMap[u.replace(/-\d+x\d+(\.\w+)$/, "$1")];
  return name ? "/images/" + name.replace(/\.\w+$/, ".webp") : u;
};
const pages = {};
for (const f of fs.readdirSync(`${R}/content-json`)) {
  const slug = f.replace(".json", "");
  if (slug.startsWith("product__")) continue;
  const blocks = JSON.parse(fs.readFileSync(`${R}/content-json/${f}`, "utf8"));
  const sections = [];
  let cur = null;
  for (const b of blocks) {
    if (b.type === "section") { cur = []; sections.push(cur); continue; }
    if (!cur) { cur = []; sections.push(cur); }
    const out = { ...b };
    // Links to this same site become relative so they navigate inside the app (same URL paths).
    const rel = (v) => v.replace(/https?:\/\/(www\.)?christembassytexasvirtualchurch\.com(\/[^"]*)?/g, (_m, _w, p) => p || "/");
    // The WordPress admin link in the sample page has no equivalent on this site: keep the words, drop the link.
    if (typeof out.html === "string") out.html = rel(out.html).replace(/<a href="\/wp-admin\/">([^<]*)<\/a>/g, "$1");
    if (typeof out.href === "string") out.href = rel(out.href);
    if (out.src && /\/wp-content\/uploads\//.test(out.src)) out.src = localize(out.src);
    cur.push(out);
  }
  pages[slug] = sections.filter((s) => s.length);
}
fs.writeFileSync(
  "src/data/content.ts",
  `/** Page content exported from the WordPress site (headings, text, images, buttons, links). GENERATED by scripts/build-content.mjs */
export type Block =
  | { type: "heading"; level: number; html: string }
  | { type: "p"; level: number; html: string }
  | { type: "li"; level: number; html: string }
  | { type: "button"; text: string; href: string; target: string }
  | { type: "image"; src: string; alt: string }
  | { type: "iframe"; src: string }
  | { type: "sectionbg"; src: string }
  | { type: "bg"; src: string };

export const CONTENT: Record<string, Block[][]> = ${JSON.stringify(pages, null, 1)};
`,
);
