// Generates src/data/products.ts, src/data/seo.ts and the server-side catalog from the
// WordPress export saved in my-site-reference/. Run: node scripts/build-data.mjs
import fs from "fs";
import * as cheerio from "cheerio";

const R = "my-site-reference";
const imgMap = JSON.parse(fs.readFileSync(`${R}/images-map.json`, "utf8")).map;
const local = (u) => {
  const name = imgMap[u] ?? imgMap[u.replace(/-\d+x\d+(\.\w+)$/, "$1")];
  if (!name) throw new Error("no local image for " + u);
  return "/images/" + name.replace(/\.\w+$/, ".webp");
};
const decode = (s) => cheerio.load(`<div>${s}</div>`)("div").text();

// ---------- products ----------
const api = JSON.parse(fs.readFileSync(`${R}/api/products.json`, "utf8"));
const sitemapOrder = fs.readFileSync(`${R}/sitemap-product.txt`, "utf8").split("\n").filter((u) => u.includes("/product/")).map((u) => u.split("/product/")[1].replace(/\/$/, ""));
// Shop-page order (as displayed on /ourstore/)
const shopInv = fs.readFileSync(`${R}/content-inventory/ourstore.md`, "utf8");
const shopOrder = [...shopInv.matchAll(/\(https:\/\/christembassytexasvirtualchurch\.com\/product\/([^/]+)\/\)/g)].map((m) => m[1]);
const bySlug = Object.fromEntries(api.map((p) => [p.slug, p]));
const products = shopOrder.map((slug) => {
  const p = bySlug[slug];
  if (!p) throw new Error("missing product " + slug);
  const inv = fs.readFileSync(`${R}/content-inventory/product__${slug}.md`, "utf8");
  const rel = [...(inv.split("## Related products")[1] ?? "").matchAll(/\/product\/([^/]+)\//g)].map((m) => m[1]);
  // The API "description" can contain leftover Divi shortcodes, so the description is taken from the
  // rendered product page ("Product Details" section) instead.
  const blocks = JSON.parse(fs.readFileSync(`${R}/content-json/product__${slug}.json`, "utf8"));
  const start = blocks.findIndex((b) => b.type === "heading" && b.html === "Product Details");
  const end = blocks.findIndex((b) => b.type === "heading" && b.html === "Related products");
  const description = blocks
    .slice(start + 1, end === -1 ? undefined : end)
    .filter((b) => b.type === "p")
    .map((b) => `<p>${b.html}</p>`)
    .join("\n");
  return {
    name: decode(p.name),
    slug,
    priceCents: Number(p.prices.price),
    regularPriceCents: Number(p.prices.regular_price),
    images: p.images.map((i) => local(i.src)),
    description,
    variations: [],
    stripePriceId: "",
    related: [...new Set(rel)].filter((s) => s !== slug),
  };
});
const missing = sitemapOrder.filter((s) => !shopOrder.includes(s));
if (missing.length) console.warn("products in sitemap but not on shop page:", missing);

fs.writeFileSync(
  "src/data/products.ts",
  `/**
 * Store products, exported from the WordPress/WooCommerce store.
 * Prices are in cents (USD). Fill in \`stripePriceId\` (price_...) once the
 * products are created in Stripe; until then checkout uses the server-side
 * catalog price. All current products are simple (no variations).
 */
export type ProductVariation = { id: string; label: string; priceCents: number; stripePriceId: string };

export type Product = {
  name: string;
  slug: string;
  priceCents: number;
  regularPriceCents: number;
  images: string[];
  /** Product description exactly as written on WordPress (HTML). */
  description: string;
  variations: ProductVariation[];
  stripePriceId: string;
  /** Slugs of the "Related products" shown on the original product page. */
  related: string[];
};

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};

export const getProduct = (slug: string) => PRODUCTS.find((p) => p.slug === slug);

export const formatPrice = (cents: number) => \`$\${(cents / 100).toFixed(2)}\`;
`,
);

// server catalog (prices looked up by the Edge Function; never trusted from the browser)
const catalog = Object.fromEntries(products.map((p) => [p.slug, { slug: p.slug, name: p.name, priceCents: p.priceCents, stripePriceId: p.stripePriceId }]));
fs.writeFileSync(
  "supabase/functions/create-checkout-session/catalog.ts",
  `// GENERATED by scripts/build-data.mjs from src/data/products.ts data. Do not edit by hand.
export type CatalogItem = { slug: string; name: string; priceCents: number; stripePriceId: string };
export const CATALOG: Record<string, CatalogItem> = ${JSON.stringify(catalog, null, 2)};
`,
);

// ---------- SEO ----------
const seo = {};
for (const f of fs.readdirSync(`${R}/html`)) {
  const slug = f.replace(".html", "");
  const $ = cheerio.load(fs.readFileSync(`${R}/html/${f}`, "utf8"));
  const meta = [];
  const title = $("title").first().text();
  $("meta").each((_, m) => {
    const name = $(m).attr("name"), prop = $(m).attr("property"), content = $(m).attr("content");
    if (content === undefined) return;
    if (name && /^(description|keywords|robots|author|twitter:.*)$/.test(name)) meta.push({ name, content });
    if (prop && /^(og:|article:)/.test(prop)) meta.push({ property: prop, content });
  });
  const canonical = $("link[rel=canonical]").attr("href") ?? null;
  const path = slug === "home" ? "/" : slug.startsWith("product__") ? `/product/${slug.slice(9)}/` : `/${slug}/`;
  const jsonld = $('script.yoast-schema-graph').first().html() ?? null;
  seo[path] = { title, canonical, meta, jsonld };
}
fs.writeFileSync(
  "src/data/seo.ts",
  `/** SEO title, description, keywords and Open Graph tags copied from the WordPress (Yoast) pages. */
export type SeoMeta = { name?: string; property?: string; content: string };
export type PageSeo = { title: string; canonical: string | null; meta: SeoMeta[]; jsonld: string | null };

export const SEO: Record<string, PageSeo> = ${JSON.stringify(seo, null, 2)};

export function seoHead(path: string) {
  const s = SEO[path];
  if (!s) return {};
  return {
    meta: [{ title: s.title }, ...s.meta],
    links: s.canonical ? [{ rel: "canonical", href: s.canonical }] : [],
    scripts: s.jsonld ? [{ type: "application/ld+json", children: s.jsonld }] : [],
  };
}
`,
);
console.log("products", products.length, "seo pages", Object.keys(seo).length);
